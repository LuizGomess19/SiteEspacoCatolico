/**
 * Generates supabase/seed.sql from the demo catalog (src/lib/demo/data.ts).
 * Usage: npm run seed:generate
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  demoBanners,
  demoCategories,
  demoCoupons,
  demoProducts,
  demoReviews,
  demoSettings,
  defaultShippingRates,
  stableUuid,
} from '../src/lib/demo/data.ts';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};

const lines: string[] = [];
lines.push('-- =============================================================================');
lines.push('-- DEMO SEED — generated by scripts/generate-seed.ts. Do not edit by hand.');
lines.push('-- All products are flagged is_demo = true and display an "Exemplo" badge.');
lines.push('-- Remove them anytime in Admin > Produtos > "Remover produtos de exemplo".');
lines.push('-- =============================================================================');
lines.push('');
lines.push('begin;');
lines.push('');

// Store settings
const s = demoSettings;
lines.push('-- Store settings');
lines.push(
  `insert into public.store_settings (id, store_name, legal_name, cnpj, email, phone, whatsapp, address, business_hours, instagram_url, facebook_url, youtube_url, origin_cep, free_shipping_threshold, pickup_enabled, pickup_address, shipping_rates, max_installments, order_expiration_hours, announcement)
values (1, ${q(s.store_name)}, ${q(s.legal_name)}, ${q(s.cnpj)}, ${q(s.email)}, ${q(s.phone)}, ${q(s.whatsapp)}, ${q(s.address)}, ${q(s.business_hours)}, ${q(s.instagram_url)}, ${q(s.facebook_url)}, ${q(s.youtube_url)}, ${q(s.origin_cep)}, ${q(s.free_shipping_threshold)}, ${q(s.pickup_enabled)}, ${q(s.pickup_address)}, ${q(JSON.stringify(defaultShippingRates))}::jsonb, ${q(s.max_installments)}, ${q(s.order_expiration_hours)}, ${q(s.announcement)})
on conflict (id) do nothing;`,
);
lines.push('');

// Categories (parents first)
lines.push('-- Categories');
const parents = demoCategories.filter((c) => !c.parent);
const children = demoCategories.filter((c) => c.parent);
for (const c of [...parents, ...children]) {
  const parentId = c.parent ? stableUuid('category:' + c.parent) : null;
  lines.push(
    `insert into public.categories (id, parent_id, name, slug, description, icon, sort_order) values (${q(stableUuid('category:' + c.slug))}, ${q(parentId)}, ${q(c.name)}, ${q(c.slug)}, ${q(c.description)}, ${q(c.icon)}, ${c.sort}) on conflict (slug) do nothing;`,
  );
}
lines.push('');

// Products
lines.push('-- Products');
demoProducts.forEach((p, index) => {
  const id = stableUuid('product:' + p.slug);
  const [w, h, l] = p.dims ?? [15, 10, 20];
  const description = `${p.description}\n\nProduto de demonstração: substitua pelas informações reais no painel administrativo.`;
  lines.push(
    `insert into public.products (id, category_id, name, slug, short_description, description, sku, price, promo_price, stock, variant_label, material, weight_grams, width_cm, height_cm, length_cm, is_featured, is_new, is_demo, sales_count, created_at) values (${q(id)}, ${q(stableUuid('category:' + p.category))}, ${q(p.name)}, ${q(p.slug)}, ${q(p.short)}, ${q(description)}, ${q('DEMO-' + String(index + 1).padStart(3, '0'))}, ${p.price}, ${q(p.promo ?? null)}, ${p.stock}, ${q(p.variantLabel ?? null)}, ${q(p.material ?? null)}, ${p.weight}, ${w}, ${h}, ${l}, ${q(!!p.featured)}, ${q(!!p.isNew)}, true, ${p.sales ?? 0}, now() - interval '${p.isNew ? index % 10 : 30 + index} days') on conflict (slug) do nothing;`,
  );
  (p.variants ?? []).forEach((v, vi) => {
    lines.push(
      `insert into public.product_variants (id, product_id, name, sku, price_override, stock, sort_order) values (${q(stableUuid('variant:' + p.slug + ':' + v.name))}, ${q(id)}, ${q(v.name)}, ${q('DEMO-' + String(index + 1).padStart(3, '0') + '-' + (vi + 1))}, ${q(v.price ?? null)}, ${v.stock}, ${vi}) on conflict do nothing;`,
    );
  });
});
lines.push('');

// Reviews
lines.push('-- Reviews (examples)');
demoReviews.forEach((r, i) => {
  lines.push(
    `insert into public.reviews (id, product_id, author_name, rating, title, comment, is_approved, is_demo, created_at) values (${q(stableUuid('review:' + i))}, ${q(stableUuid('product:' + r.product))}, ${q(r.author)}, ${r.rating}, ${q(r.title)}, ${q(r.comment)}, true, true, now() - interval '${i * 3 + 2} days') on conflict do nothing;`,
  );
});
lines.push('');

// Banners
lines.push('-- Banners');
demoBanners.forEach((b, i) => {
  lines.push(
    `insert into public.banners (id, title, subtitle, eyebrow, link_url, button_label, position, theme, sort_order) values (${q(stableUuid('banner:' + i))}, ${q(b.title)}, ${q(b.subtitle)}, ${q(b.eyebrow)}, ${q(b.link)}, ${q(b.button)}, ${q(b.position)}, ${q(b.theme)}, ${b.sort}) on conflict do nothing;`,
  );
});
lines.push('');

// Coupons
lines.push('-- Coupons');
for (const c of demoCoupons) {
  lines.push(
    `insert into public.coupons (code, description, type, value, min_order_value, max_uses_per_user) values (${q(c.code)}, ${q(c.description)}, ${q(c.type)}, ${c.value}, ${c.min}, ${q(c.perUser)}) on conflict (code) do nothing;`,
  );
}
lines.push('');
lines.push('commit;');
lines.push('');

const target = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url));
writeFileSync(target, lines.join('\n'), 'utf8');
console.log(`Seed written to ${target} (${demoProducts.length} products, ${demoCategories.length} categories).`);

